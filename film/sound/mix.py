#!/usr/bin/env python3
"""Build the film's soundtrack from three stems: narration, score and procedural foley.

    python3 film/sound/mix.py --cues film/sound/cues.json --voice VOICE_DIR --music MUSIC_DIR --out OUT_DIR [--picture out/picture.mp4]

(run from the repository root). VOICE_DIR holds one WAV per recording in cues.json "lines", named <id>.wav
(l01.wav ... l12.wav, with l09a/l09b/l09c for the split teamwork line and no l05; any rate, mono or stereo).
MUSIC_DIR holds one WAV per score cue, named <id>.wav (m1-wonder.wav ... m7-home.wav).
Narration and score are not generated by this repository; see guides/sound.md.
cues.json places everything on the film's timeline (seconds):
    lines:   [{"id", "at", "text"}]                          narration line starts and caption text
    music:   [{"id", "at", "from", "len", "fade_in", "fade_out", "gain_db"}]   a slice of each cue
    effects: [{"id", "kind", "start", "end", "pan", "gain", ...}]          procedural foley (see foley.py)
    master:  {"lufs", "true_peak", "duck_music_db", "duck_effects_db", "music_db", "effects_db"}

Writes OUT_DIR/voice.wav, music.wav, effects.wav (the stems), mix.wav (48 kHz stereo, loudness-normalized),
captions.srt and report.json. With --picture it also writes OUT_DIR/film.mp4 (picture copied, AAC 256k audio).
Needs Python 3 with numpy, scipy and soundfile (python3 -m pip install numpy scipy soundfile), and FFmpeg on PATH.
"""
import argparse
import json
import math
import re
import subprocess
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy.signal import resample_poly

import foley

SR = foley.SR


def load(path):
    x, rate = sf.read(str(path), always_2d=True, dtype='float64')
    if rate != SR:
        g = math.gcd(SR, rate)
        x = resample_poly(x, SR // g, rate // g, axis=0)
    if x.shape[1] == 1:
        x = np.repeat(x, 2, axis=1)
    return x[:, :2]


def place(buf, start_s, x):
    a = int(round(start_s * SR))
    b = min(len(buf), a + len(x))
    if b > a >= 0:
        buf[a:b] += x[:b - a]


def ramp(n, attack, release):
    g = np.ones(n)
    a, r = min(n, int(attack * SR)), min(n, int(release * SR))
    if a:
        g[:a] = 0.5 - 0.5 * np.cos(np.linspace(0, np.pi, a))
    if r:
        g[n - r:] *= 0.5 + 0.5 * np.cos(np.linspace(0, np.pi, r))
    return g


def presence(spans, n, attack=0.35, release=0.8, merge=1.2):
    """0..1 curve that rises before each narration line and falls after it; close lines merge."""
    merged = []
    for a, b in sorted(spans):
        if merged and a - merged[-1][1] < merge:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    t = np.arange(n) / SR
    p = np.zeros(n)
    for a, b in merged:
        p = np.maximum(p, np.clip(np.minimum((t - (a - attack)) / attack, ((b + release) - t) / release), 0, 1))
    return 0.5 - 0.5 * np.cos(np.pi * p)


def db(x):
    return 20 * math.log10(max(x, 1e-12))


def rms(x):
    return float(np.sqrt(np.mean(np.square(x)))) if x.size else 0.0


def loudnorm(src, dst, lufs, tp):
    """Two-pass FFmpeg loudnorm (linear mode) to the target integrated loudness and true peak."""
    f = f'loudnorm=I={lufs}:TP={tp}:LRA=18'
    r = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', '-i', str(src), '-af', f + ':print_format=json', '-f', 'null', '-'],
                       capture_output=True, text=True, check=True)
    m = json.loads(re.findall(r'\{[^{}]*\}', r.stderr)[-1])
    f2 = (f + f":measured_I={m['input_i']}:measured_TP={m['input_tp']}:measured_LRA={m['input_lra']}"
          f":measured_thresh={m['input_thresh']}:offset={m['target_offset']}:linear=true")
    subprocess.run(['ffmpeg', '-hide_banner', '-v', 'error', '-y', '-i', str(src), '-af', f2, '-ar', str(SR), '-c:a', 'pcm_s24le', str(dst)], check=True)
    r = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', '-i', str(dst), '-af', f + ':print_format=json', '-f', 'null', '-'],
                       capture_output=True, text=True, check=True)
    out = json.loads(re.findall(r'\{[^{}]*\}', r.stderr)[-1])
    return {'lufs': float(out['input_i']), 'true_peak': float(out['input_tp']), 'lra': float(out['input_lra'])}


def srt_time(t):
    ms = int(round(t * 1000))
    return f'{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--cues', required=True); ap.add_argument('--voice', required=True); ap.add_argument('--music', required=True)
    ap.add_argument('--out', required=True); ap.add_argument('--picture'); ap.add_argument('--seed', type=int, default=20261030)
    a = ap.parse_args()
    cues = json.loads(Path(a.cues).read_text())
    M = {'lufs': -14.0, 'true_peak': -1.5, 'duck_music_db': -9.0, 'duck_effects_db': -4.0, 'music_db': -12.0, 'effects_db': -15.0}
    M.update(cues.get('master', {}))
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    n = int(round(cues['duration'] * SR))

    # narration
    voice, spans, captions = np.zeros((n, 2)), [], []
    for ln in cues['lines']:
        x = load(Path(a.voice) / f"{ln['id']}.wav")
        place(voice, ln['at'], x)
        spans.append((ln['at'], ln['at'] + len(x) / SR))
        captions.append((ln['at'], ln['at'] + len(x) / SR, ln['text']))
    v_rms = rms(voice[np.abs(voice).max(axis=1) > 1e-4]) or 0.05

    # score: each cue is a slice of its take with its own fades, levelled against the narration
    music = np.zeros((n, 2))
    for c in cues['music']:
        x = load(Path(a.music) / f"{c['id']}.wav")
        s0 = int(c.get('from', 0) * SR); x = x[s0:s0 + int(c['len'] * SR)]
        x = x * ramp(len(x), c.get('fade_in', 0.5), c.get('fade_out', 1.5))[:, None]
        level = rms(x[len(x) // 8: -len(x) // 8 or None]) or 1
        x *= v_rms * 10 ** ((M['music_db'] + c.get('gain_db', 0)) / 20) / level
        place(music, c['at'], x)

    # foley
    effects = np.zeros((n, 2))
    for e in cues['effects']:
        x = foley.synth_event(e, a.seed)
        if x.ndim == 1:
            x = foley.pan_mono(x, e.get('pan', 0))
        level = rms(x)
        if not level or not np.isfinite(level):
            continue
        place(effects, e['start'], x * v_rms * 10 ** ((M['effects_db'] + e.get('gain', 0)) / 20) / level)
    effects = foley.room_reverb(effects, a.seed, -16.0)

    # duck the beds under the narration, sum, and protect the peaks before loudness normalization
    p = presence(spans, n)[:, None]
    music *= 10 ** (M['duck_music_db'] * p / 20)
    effects *= 10 ** (M['duck_effects_db'] * p / 20)
    tail = ramp(n, 0, cues.get('tail_fade', 2.0))[:, None]
    music *= tail; effects *= tail
    mix = voice + music + effects
    peak = np.abs(mix).max()
    if peak > 0.89:
        mix *= 0.89 / peak; voice *= 0.89 / peak; music *= 0.89 / peak; effects *= 0.89 / peak

    for name, x in (('voice', voice), ('music', music), ('effects', effects)):
        sf.write(str(out / f'{name}.wav'), x, SR, subtype='PCM_24')
    sf.write(str(out / 'mix-raw.wav'), mix, SR, subtype='PCM_24')
    meas = loudnorm(out / 'mix-raw.wav', out / 'mix.wav', M['lufs'], M['true_peak'])
    (out / 'mix-raw.wav').unlink()

    # speech-to-bed ratio while narration plays (dB): the words must sit clearly above music and effects
    inside = p[:, 0] > 0.99
    ratio = db(rms(voice[inside]) / max(rms((music + effects)[inside]), 1e-9)) if inside.any() else None
    (out / 'captions.srt').write_text(''.join(f'{i}\n{srt_time(s)} --> {srt_time(e + 0.4)}\n{t}\n\n'
                                              for i, (s, e, t) in enumerate(captions, 1)))
    report = {**meas, 'speech_to_bed_db': round(ratio, 1) if ratio is not None else None, 'duration': cues['duration'],
              'lines': len(cues['lines']), 'music_cues': len(cues['music']), 'effects': len(cues['effects'])}
    if a.picture:
        # AAC can overshoot the true-peak ceiling on bright syllables: measure the encoded file and, if it went over,
        # re-encode with the overshoot taken off the whole mix.
        trim = 0.0
        for _ in range(3):
            subprocess.run(['ffmpeg', '-hide_banner', '-v', 'error', '-y', '-i', a.picture, '-i', str(out / 'mix.wav'), '-map', '0:v', '-map', '1:a',
                            '-c:v', 'copy', '-af', f'volume={trim}dB', '-c:a', 'aac', '-b:a', '256k', '-ar', str(SR), '-shortest',
                            '-movflags', '+faststart', str(out / 'film.mp4')], check=True)
            r = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', '-i', str(out / 'film.mp4'), '-af', 'loudnorm=print_format=json', '-f', 'null', '-'],
                               capture_output=True, text=True, check=True)
            tp = float(json.loads(re.findall(r'\{[^{}]*\}', r.stderr)[-1])['input_tp'])
            if tp <= M['true_peak'] + 0.5:
                break
            trim -= tp - M['true_peak'] + 0.2
        report.update(film=str(out / 'film.mp4'), film_true_peak=tp, film_trim_db=round(trim, 2))
    (out / 'report.json').write_text(json.dumps(report, indent=1))
    print(json.dumps(report, indent=1))


if __name__ == '__main__':
    main()
